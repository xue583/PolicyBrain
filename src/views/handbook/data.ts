export const handbookPath = (chapterId?: number, sectionId?: number) => {
  if (!chapterId) return '/handbook'
  return sectionId
    ? `/handbook/${chapterId}/${sectionId}`
    : `/handbook/${chapterId}`
}

export const findHandbookChapter = (id?: string | number) =>
  handbookChapters.find((item) => String(item.id) === String(id)) ??
  handbookChapters[0]!
